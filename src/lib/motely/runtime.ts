// Must match the path the host serves motely-wasm's bin/ at. Used by main-thread
// hooks, workers, and Storybook staticDir alike.
export const MOTELY_BIN_PATH = "/motely-wasm/bin";

// File System for the JAML library: motely-wasm@23 removed the engine-side ops
// (IFileMounter / pickRoot / mountRoot / readTextFile / writeTextFile) and the
// `@rewaffle/bootsharp-file-system` peer. But JAML files are plain text, so the
// library doesn't need the engine at all — useJamlLibrary now backs the mount
// directly on the browser File System Access API. These helpers report whether
// that API is actually available (Chromium-based browser over https), so the
// "unsupported" path is honest rather than faked.
export function isFileSystemReady(): boolean {
    return (
        typeof window !== "undefined" &&
        window.isSecureContext === true &&
        typeof (window as unknown as { showDirectoryPicker?: unknown }).showDirectoryPicker === "function"
    );
}

/** The reason the File System Access API is unavailable, or null when it's ready. */
export function getFileSystemError(): unknown {
    return isFileSystemReady()
        ? null
        : new Error("This browser has no File System Access API (needs a Chromium-based browser over https).");
}

// Single boot promise: boot() runs exactly once and is awaited by every caller.
let bootPromise: Promise<void> | null = null;

export async function ensureMotelyReady(): Promise<void> {
    if (bootPromise) return bootPromise;
    if (bootsharp.getStatus() !== bootsharp.BootStatus.Standby) return;
    bootPromise = (async () => {
        // motely-wasm is an EMBEDDED build (the runtime is inlined into the JS as
        // base64 — see dist/generated/resources.g.mjs), so boot() takes no args and
        // needs no served binaries.
        await bootsharp.boot();
    })();
    return bootPromise;
}
